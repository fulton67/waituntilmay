// BUILDER Phase B build: kit/icons/svg -> kit/templates/icons.js; engine metadata -> kit/templates/{id}/slots.json;
// kit/templates/render.html (with the treatment filter inlined); then copies the runtime to public/brand/ostad/kit/ so the
// builder page, the server renderer and the CLI all load the same files.  usage: node brand/scripts/templates_build.mjs
import fs from "node:fs"; import path from "node:path"; import { fileURLToPath, pathToFileURL } from "node:url";
const BR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), ".."); const K = path.join(BR, "kit"); const TP = path.join(K, "templates");
const ROOT = path.resolve(BR, ".."); const PUB = path.join(ROOT, "public", "brand", "ostad", "kit");

const icons = Object.fromEntries(fs.readdirSync(path.join(K, "icons", "svg")).filter((f) => f.endsWith(".svg")).sort()
  .map((f) => [f.slice(0, -4), fs.readFileSync(path.join(K, "icons", "svg", f), "utf8").trim().replace(/ width="24" height="24"/, "")]));
fs.writeFileSync(path.join(TP, "icons.js"), "// generated by brand/scripts/templates_build.mjs from kit/icons/svg\nexport const ICONS = " + JSON.stringify(icons, null, 1) + ";\n");
// caption keywords per icon (kit/icons/icons.json), used by auto.js to pick list icons
fs.appendFileSync(path.join(TP, "icons.js"), "export const ICON_KEYWORDS = " + JSON.stringify(Object.fromEntries(JSON.parse(fs.readFileSync(path.join(K, "icons", "icons.json"), "utf8")).icons.map((i) => [i.name, i.keywords]))) + ";\n");

const eng = await import(pathToFileURL(path.join(TP, "engine.js")).href + "?v=" + Date.now());
const index = [];
for (const id of Object.keys(eng.TEMPLATES)) {
  fs.mkdirSync(path.join(TP, id), { recursive: true });
  const s = eng.slotsSchema(id); fs.writeFileSync(path.join(TP, id, "slots.json"), JSON.stringify(s, null, 1) + "\n"); index.push({ id, name: s.name, cluster: s.cluster, board_blocks: s.board_blocks });
}
fs.writeFileSync(path.join(TP, "index.json"), JSON.stringify(index, null, 1) + "\n");

const filt = fs.readFileSync(path.join(K, "components", "treatment-filter.svg"), "utf8").trim();
fs.writeFileSync(path.join(TP, "render.html"), `<!doctype html>
<!-- generated by brand/scripts/templates_build.mjs. Renders posts with kit/templates/engine.js; used by the builder preview,
     the server PNG route and brand/post.py. Call window.OK.render(spec); each .ok element is one PNG page. -->
<meta charset="utf-8"><meta name="robots" content="noindex">
<link rel="stylesheet" href="https://use.typekit.net/vzz0hgt.css">
<link rel="stylesheet" href="../kit.css"><link rel="stylesheet" href="templates.css">
<style>html,body{margin:0;background:transparent}#stage{display:flex;flex-direction:column;gap:40px;align-items:flex-start;width:max-content}</style>
${filt}
<div id="stage"></div>
<script type="module">
import * as E from "./engine.js";
import * as A from "./auto.js";
window.OK = { ...E, auto: A.auto, parse: A.parse, render: (spec) => E.render(document.getElementById("stage"), spec).then((r) => ({ fonts: r.fonts, warnings: r.warnings, pages: r.pages.length, w: r.w, h: r.h })) };
const q = new URLSearchParams(location.hash.slice(1)); if (q.get("spec")) window.OK.render(JSON.parse(q.get("spec"))).then((r) => (window.__done = r));
window.__ready = true;
</script>
`);

// copy runtime to public/
const copy = (src, dst) => { fs.mkdirSync(path.dirname(dst), { recursive: true }); fs.copyFileSync(src, dst); };
fs.rmSync(PUB, { recursive: true, force: true });
for (const f of ["kit.css", "tokens.css", "palette.json"]) copy(path.join(K, f), path.join(PUB, f));
for (const f of fs.readdirSync(path.join(K, "components"))) copy(path.join(K, "components", f), path.join(PUB, "components", f));
for (const f of ["engine.js", "auto.js", "icons.js", "templates.css", "render.html", "index.json"]) copy(path.join(TP, f), path.join(PUB, "templates", f));
for (const id of Object.keys(eng.TEMPLATES)) {
  copy(path.join(TP, id, "slots.json"), path.join(PUB, "templates", id, "slots.json"));
  for (const s of ["4x5", "1x1", "9x16"]) { const t = path.join(TP, id, `thumb_${s}.png`); if (fs.existsSync(t)) copy(t, path.join(PUB, "templates", id, `thumb_${s}.png`)); }
}
// sample photos (scripts/kit_photos.py)
const PH = path.join(TP, "photos"); if (fs.existsSync(PH)) for (const f of fs.readdirSync(PH)) copy(path.join(PH, f), path.join(PUB, "templates", "photos", f));
console.log(`${Object.keys(icons).length} icons, ${index.length} templates -> ${path.relative(ROOT, PUB)}`);

# round trip: every --ok-* in kit/tokens.css is represented, same value
by_var = {}
for p, t in flat:
    cv = t.get("$extensions", {}).get("com.ostad", {}).get("css_var")
    if cv: by_var[cv] = t
mism, covered = [], 0
for k, v in VARS.items():
    t = by_var.get(f"--ok-{k}")
    if not t: continue
    covered += 1; e = t["$extensions"]["com.ostad"]; want = v.strip()
    got = e.get("container_value") or (", ".join(f'"{x}"' if x not in ("Arial", "Inter", "sans-serif") else x for x in t["$value"]) if t["$type"] == "fontFamily" else str(t["$value"]))
    if t["$type"] == "number" and not want.endswith(("cqw", "cqh", "em")):
        if abs(float(want) - float(t["$value"])) > 1e-9: mism.append((k, want, got))
    elif t["$type"] == "dimension" and want.endswith("em"):
        if want != got: mism.append((k, want, got))
    elif want.replace(" ", "") != got.replace(" ", ""): mism.append((k, want, got))
# type roles live in typography tokens: --ok-{role}-size (cqw) must equal the 4x5 fontSize, and lh/track/weight the same values
for role in spec["roles"]:
    tv = T["typography"]["4x5"][role]["$value"]; covered += 4
    if abs(cqw_px(VARS[f"{role}-size"]) - float(tv["fontSize"][:-2])) > 0.06: mism.append((f"{role}-size", VARS[f"{role}-size"], tv["fontSize"]))
    if float(VARS[f"{role}-lh"]) != float(tv["lineHeight"]): mism.append((f"{role}-lh", VARS[f"{role}-lh"], tv["lineHeight"]))
    if VARS[f"{role}-track"].strip() != tv["letterSpacing"]: mism.append((f"{role}-track", VARS[f"{role}-track"], tv["letterSpacing"]))
    if int(VARS[f"{role}-weight"]) != int(tv["fontWeight"]): mism.append((f"{role}-weight", VARS[f"{role}-weight"], tv["fontWeight"]))
    for x in ("size", "lh", "track", "weight"): by_var[f"--ok-{role}-{x}"] = True
skipped = sorted(k for k in VARS if f"--ok-{k}" not in by_var)  # *-rgb are derived from the colour tokens; dot = hairline x 5.6
chk = {"css_vars": len(VARS), "covered": covered, "mismatches": mism, "not_tokenised": skipped, "tokens": len(flat), "motion": "motion" in T}
json.dump(chk, open(OUT / "tokens.check.json", "w", encoding="utf-8"), indent=1)
print(json.dumps({k: v for k, v in chk.items() if k != "not_tokenised"}), "not tokenised:", len(skipped))

# ---------- builds ----------
def walk(o, path=()):
    for k, v in o.items():
        if k.startswith("$"): continue
        if isinstance(v, dict) and "$value" in v: yield path + (k,), v
        elif isinstance(v, dict): yield from walk(v, path + (k,))
flat = list(walk(T))
def cssval(t):
    v = t["$value"]
    if t["$type"] == "fontFamily": return ", ".join(f'"{x}"' if " " in x or "-" in x else x for x in v)
    if t["$type"] == "cubicBezier": return f"cubic-bezier({', '.join(str(x) for x in v)})"
    if t["$type"] == "shadow": return "none"
    if t["$type"] == "typography": return None
    return str(v)

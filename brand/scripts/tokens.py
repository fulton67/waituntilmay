def cqw_px(v): return round(float(v.replace("cqw", "")) * W / 100, 2)
def ext(cite, **kw): return {"com.ostad": {"cite": cite, **kw}}
def tok(t, v, d=None, cite=None, **kw):
    o = {"$type": t, "$value": v}
    if d: o["$description"] = d
    if cite or kw: o["$extensions"] = ext(cite, **kw)
    return o
def dim(name, cite, d=None):
    v = VARS[name].strip()

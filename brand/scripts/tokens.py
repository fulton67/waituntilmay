# ASE (Adobe Swatch Exchange 1.0): big-endian; group start, colour entries (RGB float), group end
def ase(colors, group="Ostad"):
    def ustr(s): b = (s + "\0").encode("utf-16-be"); return struct.pack(">H", len(s) + 1) + b
    blocks = []
    g = ustr(group); blocks.append(struct.pack(">HI", 0xC001, len(g)) + g)
    for name, hx in colors:
        r, gg, bb = (int(hx[i:i + 2], 16) / 255 for i in (1, 3, 5))
        body = ustr(name) + b"RGB " + struct.pack(">fff", r, gg, bb) + struct.pack(">H", 2)  # 2 = normal (process)
        blocks.append(struct.pack(">HI", 0x0001, len(body)) + body)
    blocks.append(struct.pack(">HI", 0xC002, 0))
    return b"ASEF" + struct.pack(">HHI", 1, 0, len(blocks)) + b"".join(blocks)
(OUT / "ae" / "ostad.ase").write_bytes(ase([(f"ostad {k}", v["$value"]) for k, v in T["color"].items()]))

